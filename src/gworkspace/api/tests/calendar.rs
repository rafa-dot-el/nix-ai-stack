mod common;

use chrono::{NaiveDate, TimeZone, Utc};
use gworkspace_api::{calendar::{event, render_ical, render_org, sort, timezone, window, Calendar}, Session};
use serde_json::json;

fn d(y: i32, m: u32, day: u32) -> NaiveDate {
    NaiveDate::from_ymd_opt(y, m, day).unwrap()
}

fn all_day() -> serde_json::Value {
    json!({"id": "a", "summary": "Trip\nabroad", "start": {"date": "2026-06-01"}, "end": {"date": "2026-06-03"}, "description": "x\r\ny", "location": "  "})
}

fn timed() -> serde_json::Value {
    json!({"id": "t", "summary": "", "start": {"dateTime": "2026-06-01T09:00:00+02:00"}, "end": {"dateTime": "2026-06-01T10:30:00+02:00"}, "recurringEventId": "r"})
}

#[test]
fn events_are_normalised() {
    let a = event(&all_day()).unwrap();
    assert!(a.all_day && a.start_date == Some(d(2026, 6, 1)) && a.end_date_exclusive == Some(d(2026, 6, 3)));
    assert_eq!((a.summary.as_str(), a.description.as_deref(), a.location.as_deref()), ("Trip abroad", Some("x\ny"), None));
    let t = event(&timed()).unwrap();
    assert_eq!(t.summary, "(no title)");
    assert_eq!(t.start_utc, Some(Utc.with_ymd_and_hms(2026, 6, 1, 7, 0, 0).unwrap()));
    assert!(t.recurring);
    let one_day = event(&json!({"id": "o", "start": {"date": "2026-06-05"}})).unwrap();
    assert_eq!(one_day.end_date_exclusive, Some(d(2026, 6, 6)));
    assert!(event(&json!({"id": "", "start": {"date": "2026-06-05"}})).is_none());
    assert!(event(&json!({"id": "x"})).is_none());
}

#[test]
fn timezones_and_windows() {
    assert_eq!(timezone("UTC").unwrap(), chrono_tz::UTC);
    assert_eq!(timezone("GMT").unwrap(), chrono_tz::Etc::GMT);
    assert_eq!(timezone("Europe/Warsaw").unwrap(), chrono_tz::Europe::Warsaw);
    assert!(timezone("Mars/Base").unwrap_err().contains("Mars/Base"));
    let (from, until) = window(d(2026, 7, 10), chrono_tz::Europe::Warsaw, 1, 2).unwrap();
    assert_eq!(from, Utc.with_ymd_and_hms(2026, 7, 8, 22, 0, 0).unwrap(), "midnight Warsaw (CEST) on the 9th");
    assert_eq!(until, Utc.with_ymd_and_hms(2026, 7, 12, 22, 0, 0).unwrap(), "exclusive: midnight on the 13th");
    assert!(window(d(2026, 7, 10), chrono_tz::UTC, -1, 0).is_err());
}

#[test]
fn org_rendering() {
    let mut evs = vec![event(&timed()).unwrap(), event(&all_day()).unwrap()];
    sort(&mut evs);
    let org = render_org(&evs, chrono_tz::Europe::Warsaw);
    let expected = "#+TITLE: Google Calendar (imported)\n#+FILETAGS: :gcal:\n# Regenerated by gcal sync; edits here are overwritten.\n\n\
* Trip abroad\n:PROPERTIES:\n:GCAL_ID: a\n:END:\n<2026-06-01 Mon>--<2026-06-02 Tue>\n#+begin_example\nx\ny\n#+end_example\n\n\
* (no title)\n:PROPERTIES:\n:GCAL_ID: t\n:RECURRING: t\n:END:\n<2026-06-01 Mon 09:00-10:30>\n";
    assert_eq!(org, expected);
}

#[test]
fn ical_escapes_uses_crlf_and_folds_long_lines() {
    let long = "word ".repeat(30);
    let ev = event(&json!({"id": "x;1", "summary": format!("a,b;c\\d {long}"), "start": {"dateTime": "2026-06-01T09:00:00Z"}})).unwrap();
    let ics = render_ical(&[ev], Utc.with_ymd_and_hms(2026, 1, 2, 3, 4, 5).unwrap());
    assert!(ics.starts_with("BEGIN:VCALENDAR\r\nVERSION:2.0\r\nPRODID:-//rafa//gworkspace gcal//EN\r\n"), "{ics}");
    assert!(ics.contains(&format!("{}\r\n", r"UID:x\;1@gsuite.local")), "UIDs stay stable across the port");
    assert!(ics.contains("DTSTAMP:20260102T030405Z\r\n") && ics.contains("DTSTART:20260601T090000Z\r\n"));
    assert!(ics.ends_with("END:VEVENT\r\nEND:VCALENDAR\r\n"));
    for line in ics.split("\r\n") {
        assert!(line.len() <= 75, "unfolded line of {} octets: {line:?}", line.len());
    }
    let unfolded = ics.replace("\r\n ", "");
    assert!(unfolded.contains(&format!("{}{}", r"SUMMARY:a\,b\;c\\d ", long.trim_end())), "{unfolded}");
}

#[test]
fn folding_never_splits_a_character() {
    let ev = event(&json!({"id": "u", "summary": "ł".repeat(80), "start": {"date": "2026-06-01"}})).unwrap();
    let ics = render_ical(&[ev], Utc.with_ymd_and_hms(2026, 1, 1, 0, 0, 0).unwrap());
    for line in ics.split("\r\n") {
        assert!(line.len() <= 75);
    }
    assert!(ics.replace("\r\n ", "").contains(&format!("SUMMARY:{}", "ł".repeat(80))));
}

#[tokio::test]
async fn listing_pages_dedups_and_sorts() {
    let s = common::stub(vec![
        (200, json!({"items": [timed(), {"id": "bad"}], "nextPageToken": "p"})),
        (200, json!({"items": [all_day(), timed()]})),
        (200, timed()),
    ])
    .await;
    let c = Calendar { session: Session::new("t", format!("{}/calendar/v3", s.base)).unwrap() };
    let from = Utc.with_ymd_and_hms(2026, 6, 1, 0, 0, 0).unwrap();
    let evs = c.events("primary", from, from + chrono::Duration::days(2)).await.unwrap();
    assert_eq!(evs.iter().map(|e| e.id.as_str()).collect::<Vec<_>>(), vec!["a", "t"]);
    let first = &s.seen()[0].target;
    assert!(first.starts_with("/calendar/v3/calendars/primary/events?timeMin=2026-06-01T00%3A00%3A00Z&timeMax=2026-06-03T00%3A00%3A00Z&singleEvents=true&orderBy=startTime&maxResults=250"), "{first}");
    assert_eq!(c.get("me@x.org", "t").await.unwrap().id, "t");
    assert_eq!(s.seen()[2].target, "/calendar/v3/calendars/me@x.org/events/t");
}

fn has_local_variables(org: &str) -> bool {
    org.to_ascii_lowercase().contains("local variables:")
}

#[test]
fn a_location_cannot_start_a_line() {
    let ev = event(&json!({"id": "l", "summary": "S", "location": "Room 1\n* Injected heading\n#+STARTUP: x", "start": {"date": "2026-06-01"}})).unwrap();
    let org = render_org(&[ev], chrono_tz::UTC);
    assert!(org.lines().all(|l| !l.starts_with("* Injected") && !l.starts_with("#+STARTUP")), "{org}");
    assert!(org.contains("  Location: Room 1 * Injected heading #+STARTUP: x\n"), "{org}");
}

#[test]
fn a_description_is_inert() {
    let desc = "notes\n* fake heading\n#+begin_src emacs-lisp\n(x)\n#+end_src\n# Local Variables:\n# eval: (shell-command \"id\")\n# End:";
    let ev = event(&json!({"id": "d", "summary": "S", "description": desc, "start": {"date": "2026-06-01"}})).unwrap();
    let org = render_org(&[ev], chrono_tz::UTC);
    assert!(!has_local_variables(&org), "{org}");
    assert!(org.contains("#+begin_example\nnotes\n,* fake heading\n,#+begin_src emacs-lisp\n(x)\n,#+end_src\n"), "{org}");
    assert!(org.lines().filter(|l| l.trim_start().starts_with("#+end_example")).count() == 1, "{org}");
}

#[test]
fn summaries_cannot_assemble_a_local_variables_block() {
    let evs: Vec<_> = ["Local Variables:", "eval: (shell-command \"id\")", "End:"]
        .iter()
        .enumerate()
        .map(|(i, s)| event(&json!({"id": format!("{i}"), "summary": s, "start": {"date": "2026-06-01"}})).unwrap())
        .collect();
    let org = render_org(&evs, chrono_tz::UTC);
    assert!(!has_local_variables(&org), "{org}");
    let loc = event(&json!({"id": "x", "summary": "s", "location": "lOcAl VaRiAbLeS: here", "start": {"date": "2026-06-01"}})).unwrap();
    assert!(!has_local_variables(&render_org(&[loc], chrono_tz::UTC)));
}
